#!/usr/bin/env python3
"""Generates stick/statick_shapes.py (the Stick's triangle data) from the approved prototype's geometry (design/statick-prototype/statick.js).

The M5GFX canvas on the Stick has fillTriangle but no polygon fill, so the character's polygons (hair, quiff layers, nose shadow) are split into triangles
here, once, by ear clipping, and written as plain integer tuples. The other shapes (rounded rectangles, circles, arcs, lines) are drawn by stick/robot.py with the same constants.
Needs Node.js (only to evaluate statick.js); run from the project root:  python3 tools/gen_statick_shapes.py   (add --check to verify the committed file is current).
"""
import json
import shutil
import subprocess
import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
ENGINE = ROOT / "design" / "statick-prototype" / "statick.js"
OUT = ROOT / "stick" / "statick_shapes.py"
# the first seven polygons head() emits for a state whose quiff is not rotated (the "ready" state at t = 0), in this order
NAMES = ("HAIR_CAP", "HAIR_SIDES", "HAIR_SHADE", "QUIFF_BASE", "QUIFF_MID", "QUIFF_TIPS", "NOSE")


def area(points):
    return sum(points[i][0] * points[(i + 1) % len(points)][1] - points[(i + 1) % len(points)][0] * points[i][1] for i in range(len(points))) / 2.0


def inside(p, a, b, c):
    def sign(p1, p2, p3):
        return (p1[0] - p3[0]) * (p2[1] - p3[1]) - (p2[0] - p3[0]) * (p1[1] - p3[1])
    d1, d2, d3 = sign(p, a, b), sign(p, b, c), sign(p, c, a)
    return not (((d1 < 0) or (d2 < 0) or (d3 < 0)) and ((d1 > 0) or (d2 > 0) or (d3 > 0)))


def triangulate(points):
    """Ear clipping for a simple polygon (any winding). Returns (points, [(i, j, k), ...]) with indices into the returned points."""
    pts = [tuple(p) for p in points]
    if area(pts) < 0:
        pts.reverse()
    idx = list(range(len(pts)))
    out = []
    guard = 0
    while len(idx) > 3 and guard < 10000:
        guard += 1
        for k in range(len(idx)):
            i0, i1, i2 = idx[k - 1], idx[k], idx[(k + 1) % len(idx)]
            a, b, c = pts[i0], pts[i1], pts[i2]
            cross = (b[0] - a[0]) * (c[1] - a[1]) - (b[1] - a[1]) * (c[0] - a[0])
            if cross <= 0:
                continue
            if any(inside(pts[j], a, b, c) for j in idx if j not in (i0, i1, i2) and pts[j] not in (a, b, c)):
                continue
            out.append((i0, i1, i2))
            idx.pop(k)
            break
        else:
            raise ValueError("polygon cannot be triangulated")
    out.append(tuple(idx))
    return pts, out


def load_polygons():
    node = shutil.which("node")
    if not node:
        raise SystemExit("Node.js is needed to read statick.js")
    script = "global.window={};require(process.argv[1]);const it=window.Statick.scene('ready',0).filter(i=>i.k==='poly').slice(0,7);console.log(JSON.stringify(it.map(i=>i.pts)));"
    done = subprocess.run([node, "-e", script, str(ENGINE)], capture_output=True, text=True, timeout=60)
    if done.returncode != 0:
        raise SystemExit(done.stderr)
    return json.loads(done.stdout)


def render():
    polygons = load_polygons()
    lines = ['# statick_shapes.py - GENERATED by tools/gen_statick_shapes.py from design/statick-prototype/statick.js. Do not edit by hand.',
             "# Each shape is (points, triangles): the polygon's corners and its split into triangles (indices into the points), for the canvas's fillTriangle",
             "# (the canvas has no polygon fill). robot.py rotates the points once per angle and caches the result, so drawing a frame is only fillTriangle calls.", ""]
    for name, polygon in zip(NAMES, polygons):
        rounded = [(round(x), round(y)) for x, y in polygon]
        pts, tris = triangulate(rounded)
        covered = sum(abs(area([pts[i] for i in t])) for t in tris)
        assert abs(covered - abs(area(rounded))) < 1e-6, (name, covered)      # the pieces add up to the whole
        lines.append(f"{name} = (")
        lines.append("    (" + ", ".join(f"({x}, {y})" for x, y in pts) + ",),")
        lines.append("    (" + ", ".join(f"({a}, {b}, {c})" for a, b, c in tris) + ",),")
        lines.append(")")
        lines.append("")
    return "\n".join(lines)


if __name__ == "__main__":
    text = render()
    if "--check" in sys.argv:
        sys.exit(0 if OUT.exists() and OUT.read_text() == text else 1)
    OUT.write_text(text)
    print(f"wrote {OUT.relative_to(ROOT)}: {text.count(chr(10))} lines")
