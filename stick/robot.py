# robot.py - Statick, the animated character of the StickS3 voice assistant (135x240 portrait).
# Draws into one off-screen canvas and pushes whole frames, so there is no flicker.
# update() only redraws when the picture actually changes, at most every FRAME_MS.
#
# The interface is the same as the previous robot face (Robot.set / update / relabel / hold, the same state names), so nothing that calls it changes.
# The drawing follows the approved prototype (design/statick-prototype/statick.js). The canvas has fillTriangle but no polygon fill, so the hair is
# drawn from the triangles in statick_shapes.py (generated by tools/gen_statick_shapes.py); everything else uses rounded rectangles, circles, arcs and
# thick lines. The mouth while speaking follows the level given to update(); it is whatever the caller passes (the loudness of the audio the Stick plays
# itself, or a generic pattern when another device plays the sound).
import gc
import M5
import math
import random
import time
import statick_shapes as shapes

W, H = 135, 240
FRAME_MS = 60

TEAL = 0x19F5E1
TEAL_DIM = 0x0B5F58
RED = 0xFF3B3B
ORANGE = 0xFF8A3D
WHITE = 0xFFFFFF
GREY = 0x8A9BA0
BLACK = 0x000000
SKIN = 0xF1C8A0
SHADE = 0xD49F72
HAIR = 0x2B2833
BLOND = 0xE5B53A
BLOND_HI = 0xFFE07A
BLOND_TIP = 0xFFF4B8
FRAME_C = 0xD8DEE2
INK = 0x1E1C27
MOUTH_C = 0x8B3A3A
TONGUE = 0xE9798B
GOLD = 0xE9B824
BLUSH = 0xE58C8C
XEYE = 0x8E2A1A
REC_OFF = 0x3A0F0F

PIVOT_X, PIVOT_Y = 67, 66          # the quiff swings about its base
SWAY = (0, 1, 1, 0, -1, -1)        # degrees, one step about every half second


def _now():
    return time.ticks_ms()


def _since(t):
    return time.ticks_diff(time.ticks_ms(), t)


def _i(v):
    return int(v + 0.5) if v >= 0 else -int(-v + 0.5)


_DIM = {}
_TRIG = {}
_CORNER = tuple((math.cos(k * 22.5 * math.pi / 180.0), math.sin(k * 22.5 * math.pi / 180.0)) for k in range(4))     # a rounded corner in 22.5-degree steps
_CACHE = {}          # computed geometry, keyed by what it depends on: a frame is then only drawing calls (sin/cos and per-point Python are slow on the Stick)


def _dim(color):
    v = _DIM.get(color)
    if v is None:
        r, g, b = (color >> 16) & 255, (color >> 8) & 255, color & 255
        v = _DIM[color] = ((r * 5 // 8) << 16) | ((g * 5 // 8) << 8) | (b * 5 // 8)      # the night palette: about 62 percent
    return v


def _cs(deg):
    """(cos, sin) of a whole number of degrees, computed once (the Stick's sin/cos take about 0.2 ms each)."""
    v = _TRIG.get(deg)
    if v is None:
        v = _TRIG[deg] = (math.cos(deg * math.pi / 180.0), math.sin(deg * math.pi / 180.0))
    return v


_SHAPES = (shapes.HAIR_CAP, shapes.HAIR_SIDES, shapes.HAIR_SHADE, shapes.QUIFF_BASE, shapes.QUIFF_MID, shapes.QUIFF_TIPS, shapes.NOSE)
CAP, SIDES, SHADE_S, QBASE, QMID, QTIPS, NOSE_S = 0, 1, 2, 3, 4, 5, 6


def _poly_tris(shape, deg, drop, dx, dy):
    """The triangles of a shape, swung about the quiff's base by deg degrees, sagged by drop pixels, moved by (dx, dy): ints, ready for fillTriangle."""
    pts, tris = shape
    out = []
    if deg or drop:
        cs, sn = _cs(deg)
        for x, y in pts:
            x, y = x - PIVOT_X, y - PIVOT_Y
            rx, ry = PIVOT_X + x * cs - y * sn, PIVOT_Y + x * sn + y * cs
            if drop and ry < PIVOT_Y:
                ry += drop * (PIVOT_Y - ry) / PIVOT_Y
            out.append((_i(rx) + dx, _i(ry) + dy))
    else:
        out = [(x + dx, y + dy) for x, y in pts]
    return tuple((out[a][0], out[a][1], out[b][0], out[b][1], out[c][0], out[c][1]) for a, b, c in tris)


def _line_geo(x1, y1, x2, y2, w):
    dx, dy = x2 - x1, y2 - y1
    length = math.sqrt(dx * dx + dy * dy) or 1.0
    nx, ny = -dy / length * (w / 2.0), dx / length * (w / 2.0)
    a, b, d, e = (_i(x1 + nx), _i(y1 + ny)), (_i(x1 - nx), _i(y1 - ny)), (_i(x2 + nx), _i(y2 + ny)), (_i(x2 - nx), _i(y2 - ny))
    r = max(1, _i(w / 2.0))
    return ((a[0], a[1], b[0], b[1], d[0], d[1]), (b[0], b[1], d[0], d[1], e[0], e[1]), (x1, y1, r), (x2, y2, r))


def _fan_geo(x, y, w, h, r, cx, cy, deg):
    """A rotated rounded rectangle (convex) as a fan of triangles from its centre."""
    cs, sn = _cs(deg)
    pts = []
    # the four corners start at -90, 0, 90 and 180 degrees: a quarter turn of the table's (cos, sin) pairs
    for ccx, ccy, quarter in ((x + w - r, y + r, 0), (x + w - r, y + h - r, 1), (x + r, y + h - r, 2), (x + r, y + r, 3)):
        for k in range(4):
            c0, s0 = _CORNER[k]
            ox, oy = ((c0, s0), (-s0, c0), (-c0, -s0), (s0, -c0))[quarter]                       # rotate (c0, s0) by `quarter` quarter-turns...
            ox, oy = oy, -ox                                                                      # ...and start at -90 degrees instead of 0
            px, py = ccx + r * ox - cx, ccy + r * oy - cy
            pts.append((_i(cx + px * cs - py * sn), _i(cy + px * sn + py * cs)))
    mx, my = (x + w / 2.0) - cx, (y + h / 2.0) - cy
    mid = (_i(cx + mx * cs - my * sn), _i(cy + mx * sn + my * cs))
    return tuple((mid[0], mid[1], pts[i][0], pts[i][1], pts[(i + 1) % len(pts)][0], pts[(i + 1) % len(pts)][1]) for i in range(len(pts)))


def _glasses_geo(dx, dy, tilt):
    """(frame triangles, lens triangles, the two eye centres, line pieces) of the glasses for this offset and tilt; computed once."""
    cx, cy = 67 + dx, 105 + dy
    cs, sn = _cs(tilt)

    def rot(px, py):
        px, py = px + dx - cx, py + dy - cy
        return _i(cx + px * cs - py * sn), _i(cy + px * sn + py * cs)
    frames = lenses = None
    if tilt:
        frames = _fan_geo(23 + dx, 85 + dy, 46, 40, 15, cx, cy, tilt) + _fan_geo(66 + dx, 85 + dy, 46, 40, 15, cx, cy, tilt)
        lenses = _fan_geo(26 + dx, 88 + dy, 40, 34, 12, cx, cy, tilt) + _fan_geo(69 + dx, 88 + dy, 40, 34, 12, cx, cy, tilt)
    pieces = []
    for kind, (p1, p2, w) in ((0, ((66, 101), (70, 101), 3)), (0, ((23, 97), (16, 105), 2)), (0, ((112, 97), (119, 105), 2)),
                              (1, ((32, 96), (35, 93), 2)), (1, ((75, 96), (78, 93), 2))):
        u, v = rot(*p1), rot(*p2)
        pieces.append((kind, _line_geo(u[0], u[1], v[0], v[1], w)))
    return frames, lenses, (rot(46, 105), rot(89, 105)), tuple(pieces)


class Robot:
    def __init__(self):
        self.c = M5.Lcd.newCanvas(W, H, 16, True)
        self.font = M5.Lcd.FONTS.Montserrat18
        self.small = M5.Lcd.FONTS.Montserrat14
        self._key = None
        self._last_draw = 0
        self.level = 0.0
        self._night = False
        try:
            if gc.threshold() < 262144:
                # A collection takes about 70 ms on this device and the default threshold (20 KB) triggered one every few frames: collect after 256 KB
                # of allocation instead (roughly every few seconds of animation). The heap has megabytes free.
                gc.threshold(262144)
        except AttributeError:
            pass                                                         # (CPython, where the tests run, has no gc.threshold)
        self.set("idle")

    # ---- public interface -------------------------------------------------
    def set(self, state, label=None, detail=None, duration_ms=None, elapsed=False):
        """Switch state. label: short status text; duration_ms: for progress bars;
        elapsed: show seconds since this state began (thinking only)."""
        self.state = state
        self.label = label
        self.detail = detail
        self.duration_ms = duration_ms
        self.elapsed = elapsed
        self.since = _now()
        self.level = 0.0
        self._look = (0, 0)
        self._next_look = _now() + random.randint(1500, 3500)
        self._next_blink = _now() + random.randint(2000, 5000)
        self._key = None
        self.update(force=True)

    def update(self, level=None, force=False):
        """Call often (e.g. every 20 ms). level: 0..1 mouth opening while speaking."""
        if level is not None:
            self.level = level
        if not force and _since(self._last_draw) < FRAME_MS:
            return
        key = self._frame()
        if force or key != self._key:
            self._key = key
            self._draw(key)
            self._last_draw = _now()

    def relabel(self, label):
        """Change the status text without restarting the state's clock."""
        self.label = label
        self._key = None
        self.update(force=True)

    def hold(self, ms):
        """Keep animating for ms milliseconds (replaces time.sleep in the app)."""
        start = _now()
        while _since(start) < ms:
            self.update()
            time.sleep_ms(20)

    # ---- animation state --------------------------------------------------
    def _blinking(self):
        now = _now()
        if time.ticks_diff(now, self._next_blink) >= 0:
            if time.ticks_diff(now, self._next_blink) > 130:
                self._next_blink = now + random.randint(2500, 6000)
                return False
            return True
        return False

    def _frame(self):
        s = self.state
        t = _since(self.since)
        sway = SWAY[(t // 500) % 6]
        if s == "idle":
            now = _now()
            if time.ticks_diff(now, self._next_look) >= 0:
                self._look = (random.choice((-4, 0, 0, 4)), random.choice((-2, 0, 0, 2)))
                self._next_look = now + random.randint(1500, 4000)
            return (s, self._look, self._blinking(), sway)
        if s == "ready":
            return (s, self._blinking(), sway)
        if s == "listening":
            progress = 0
            if self.duration_ms:
                progress = min(100, t * 100 // self.duration_ms) // 4
            return (s, (t // 500) % 2, progress)
        if s == "thinking":
            drift = (0, 2, 4, 2)[(t // 900) % 4]
            return (s, (t // 350) % 3, drift, t // 1000 if self.elapsed else None, sway)
        if s == "speaking":
            return (s, int(self.level * 6), (t // 250) % 2, self._blinking(), sway)
        if s == "dizzy":
            return (s, (t // 90) % 8, (t // 160) % 4, int(self.level * 4))
        if s == "sleeping":
            return (s, (t // 600) % 8)
        if s == "done":
            return (s, (t // 450) % 2)
        if s == "attention":
            return (s, (t // 300) % 2)
        if s == "puzzled":
            return (s, (t // 400) % 2)
        return (s, (t // 400) % 2)

    # ---- drawing helpers --------------------------------------------------
    def _col(self, color):
        return _dim(color) if self._night else color

    def _text(self, text, y, color, font=None):
        c = self.c
        c.setFont(font or self.font)
        c.setTextSize(1)
        c.setTextColor(color, BLACK)
        x = (W - c.textWidth(text)) // 2
        c.drawString(text, max(0, x), y)

    def _arc(self, x, y, r0, r1, start, span, color):
        # Draw an arc of span degrees from start, splitting it where it crosses 0.
        start %= 360
        end = start + span
        if end <= 360:
            self.c.fillArc(x, y, r0, r1, start, end, color)
        else:
            self.c.fillArc(x, y, r0, r1, start, 360, color)
            self.c.fillArc(x, y, r0, r1, 0, end - 360, color)

    def _line(self, x1, y1, x2, y2, w, color):
        """A thick line with round ends: two triangles and two circles (geometry cached, so a frame allocates next to nothing)."""
        c = self.c
        x1, y1, x2, y2 = _i(x1), _i(y1), _i(x2), _i(y2)
        key = (x1, y1, x2, y2, w)
        g = _CACHE.get(key)
        if g is None:
            if len(_CACHE) > 600:
                _CACHE.clear()
            g = _CACHE[key] = _line_geo(x1, y1, x2, y2, w)
        t = g[0]
        c.fillTriangle(t[0], t[1], t[2], t[3], t[4], t[5], color)
        t = g[1]
        c.fillTriangle(t[0], t[1], t[2], t[3], t[4], t[5], color)
        c.fillCircle(g[2][0], g[2][1], g[2][2], color)
        c.fillCircle(g[3][0], g[3][1], g[3][2], color)

    def _tris(self, sid, color, dx, dy, deg=0, drop=0):
        """Fill a pre-triangulated polygon (index into _SHAPES), optionally swung about the quiff's base by deg degrees and sagged by drop pixels."""
        key = sid | ((deg + 64) << 3) | (drop << 10) | ((dx + 64) << 14) | ((dy + 64) << 21)        # a small int: no allocation
        tris = _CACHE.get(key)
        if tris is None:
            if len(_CACHE) > 600:
                _CACHE.clear()
            tris = _CACHE[key] = _poly_tris(_SHAPES[sid], deg, drop, dx, dy)
        ft = self.c.fillTriangle
        for t in tris:
            ft(t[0], t[1], t[2], t[3], t[4], t[5], color)

    # ---- the character ----------------------------------------------------
    def _head(self, dx=0, dy=0, quiff=0, drop=0):
        c, col = self.c, self._col
        c.fillCircle(20 + dx, 120 + dy, 8, col(SKIN))                            # ears, and the one small gold stud
        c.fillCircle(115 + dx, 120 + dy, 8, col(SKIN))
        c.fillCircle(16 + dx, 127 + dy, 3, col(GOLD))
        self._tris(CAP, col(HAIR), dx, dy)                                       # dark hair: a cap and the sides
        c.fillRoundRect(21 + dx, 70 + dy, 93, 94, 34, col(SKIN))                 # the face
        self._tris(SIDES, col(HAIR), dx, dy)
        self._tris(SHADE_S, col(SHADE), dx, dy)
        self._tris(QBASE, col(BLOND), dx, dy, quiff, drop)                       # the quiff, three layers brightening to the tips
        self._tris(QMID, col(BLOND_HI), dx, dy, quiff, drop)
        self._tris(QTIPS, col(BLOND_TIP), dx, dy, quiff, drop)
        self._tris(NOSE_S, col(SHADE), dx, dy)

    def _brows(self, left, right, dx=0, dy=0):
        for x0, x1, (raise_, tilt), outer_left in ((31, 59, left, True), (76, 104, right, False)):
            y = 80 - raise_ + dy
            yo, yi = y - tilt, y + tilt
            if outer_left:
                self._line(x0 + dx, yo, x1 + dx, yi, 4, self._col(HAIR))
            else:
                self._line(x0 + dx, yi, x1 + dx, yo, 4, self._col(HAIR))

    def _eye(self, x, y, kind, a=0, b=0, w=22, h=24):
        c, col = self.c, self._col
        if kind == "open":
            c.fillRoundRect(x - w // 2, y - h // 2, w, h, min(w, h) // 2, col(WHITE))
            px = max(-(w // 2 - 6), min(w // 2 - 6, a))
            py = max(-(h // 2 - 6), min(h // 2 - 6, b))
            c.fillCircle(x + px, y + py, 6, col(INK))
            c.fillCircle(x + px - 2, y + py - 2, 2, col(WHITE))
        elif kind == "blink":
            c.fillRoundRect(x - 11, y - 2, 22, 4, 2, col(INK))
        elif kind == "closed":
            self._arc(x, y - 1, 7, 10, 25, 130, col(INK))
        elif kind == "happy":
            self._arc(x, y + 6, 7, 10, 180, 180, col(INK))
        elif kind == "x":
            self._line(x - 8, y - 8, x + 8, y + 8, 4, col(XEYE))
            self._line(x + 8, y - 8, x - 8, y + 8, 4, col(XEYE))
        elif kind == "spiral":
            c.fillCircle(x, y, 12, col(WHITE))
            self._arc(x, y, 8, 11, a * 45, 270, col(INK))
            self._arc(x, y, 3, 6, a * 45 + 180, 270, col(INK))
        elif kind == "half":
            c.fillRoundRect(x - 10, y - 4, 20, 12, 6, col(WHITE))
            c.fillCircle(x + a, y + 2, 5, col(INK))

    def _glasses(self, eyes, frame=FRAME_C, dx=0, dy=0, tilt=0):
        """Oversized thin-frame glasses with the eyes inside; tilt (degrees) swings the whole pair about its centre."""
        c, col = self.c, self._col
        fc = col(frame)
        gkey = ((dx + 64) << 12) | ((dy + 64) << 6) | (tilt + 32) | (1 << 20)                  # a small int: no allocation
        geo = _CACHE.get(gkey)
        if geo is None:
            if len(_CACHE) > 600:
                _CACHE.clear()
            geo = _CACHE[gkey] = _glasses_geo(dx, dy, tilt)
        frames, lenses, centres, pieces = geo
        ft = c.fillTriangle
        if tilt:
            for t in frames:
                ft(t[0], t[1], t[2], t[3], t[4], t[5], fc)
            skin = col(SKIN)
            for t in lenses:
                ft(t[0], t[1], t[2], t[3], t[4], t[5], skin)
        else:
            for x in (26, 69):
                c.fillRoundRect(x - 3 + dx, 85 + dy, 46, 40, 15, fc)
            for x in (26, 69):
                c.fillRoundRect(x + dx, 88 + dy, 40, 34, 12, col(SKIN))
        for (kind, a, b, w, h), (px, py) in zip(eyes, centres):
            self._eye(px, py, kind, a, b, w, h)
        white = col(WHITE)
        for kind, g in pieces:
            color = white if kind else fc
            t = g[0]
            ft(t[0], t[1], t[2], t[3], t[4], t[5], color)
            t = g[1]
            ft(t[0], t[1], t[2], t[3], t[4], t[5], color)
            c.fillCircle(g[2][0], g[2][1], g[2][2], color)
            c.fillCircle(g[3][0], g[3][1], g[3][2], color)

    def _mouth(self, kind, dx=0, dy=0, level=0, width=18, shift=0, amp=0):
        c, col = self.c, self._col
        cx, cy, ink = 67 + dx, 150 + dy, col(MOUTH_C)
        if kind == "smile":
            self._arc(cx, cy - 8, 11, 14, 28, 124, ink)
        elif kind == "bigsmile":
            self._arc(cx, cy - 10, 14, 18, 22, 136, ink)
        elif kind == "flat":
            c.fillRoundRect(cx - width // 2 + shift, cy + 1, width, 4, 2, ink)
        elif kind == "o":
            c.fillCircle(cx, cy + 3, 6, ink)
            c.fillCircle(cx, cy + 3, 3, col(TONGUE))
        elif kind == "open":
            h = 4 + level * 3                                                    # level 0..6, as the earlier face
            w = 26 + level * 4 // 6
            c.fillRoundRect(cx - w // 2, cy + 3 - h // 2, w, h, min(9, h // 2), ink)
            if h > 12:
                c.fillRoundRect(cx - w // 2 + 5, cy + 3 + h // 2 - 7, w - 10, 6, 3, col(TONGUE))
        elif kind == "wavy":
            a = 2 + amp
            for i in range(4):
                x0 = cx - 16 + i * 8
                y0 = cy + 3 + (a if i % 2 else -a)
                y1 = cy + 3 + (-a if i % 2 else a)
                self._line(x0, y0, x0 + 8, y1, 3, ink)

    def _draw(self, key):
        c = self.c
        s = key[0]
        self._night = False
        c.fillScreen(BLACK)

        if s == "idle":
            look, blink, sway = key[1], key[2], key[3]
            eye = ("blink", 0, 0, 22, 24) if blink else ("open", look[0], look[1], 22, 24)
            self._head(quiff=sway)
            self._brows((0, 0), (0, 0))
            self._glasses((eye, eye))
            self._mouth("smile")
            self._text(self.label or "Press button", 188, GREY, self.small)

        elif s == "ready":
            blink, sway = key[1], key[2]
            eye = ("blink", 0, 0, 24, 28) if blink else ("open", 0, 0, 24, 28)
            self._head(quiff=sway)
            self._brows((3, 0), (3, 0))
            self._glasses((eye, eye))
            self._mouth("flat", width=12)
            self._text(self.label or "Get ready", 180, WHITE)

        elif s == "listening":
            pulse, progress = key[1], key[2]
            eye = ("open", 0, 0, 26, 30)
            self._head(quiff=2)
            self._brows((3, 0), (3, 0))
            self._glasses((eye, eye), frame=RED if pulse else FRAME_C)
            self._mouth("o")
            c.fillCircle(14, 14, 5, RED if pulse else REC_OFF)
            c.setFont(self.small)
            c.setTextSize(1)
            c.setTextColor(RED, BLACK)
            c.drawString("REC", 24, 7)
            self._text(self.label or "Listening", 176, WHITE)
            c.fillRoundRect(17, 212, 101, 8, 4, TEAL_DIM)
            if progress:
                c.fillRoundRect(17, 212, max(8, 101 * progress // 25), 8, 4, RED)

        elif s == "thinking":
            dot, drift, seconds, sway = key[1], key[2], key[3], key[4]
            eye = ("open", -3 + drift // 2, -5, 22, 20)
            self._head(quiff=sway + 2)
            self._brows((4, -2), (0, 1))
            self._glasses((eye, eye), dy=1)
            self._mouth("flat", width=12, shift=6)
            self._text(self.label or "Thinking", 172, WHITE)
            if seconds is not None:
                self._text("%d s" % seconds, 196, GREY, self.small)
            for i in range(3):
                c.fillCircle(49 + i * 18, 224, 5, TEAL if i == dot else TEAL_DIM)

        elif s == "speaking":
            opening, bounce, blink, sway = key[1], key[2], key[3], key[4]
            eye = ("blink", 0, 0, 24, 24) if blink else ("open", 0, 0, 24, 24)
            self._head(dy=-1 if bounce else 0, quiff=sway + (1 if bounce else 0))
            self._brows((bounce, 0), (bounce, 0), dy=-1 if bounce else 0)
            self._glasses((eye, eye), dy=-1 if bounce else 0)
            self._mouth("open", dy=-1 if bounce else 0, level=opening)
            self._text(self.label or "Speaking", 188, GREY, self.small)

        elif s == "puzzled":
            wobble = key[1]
            self._head(quiff=4 if wobble else 1)
            self._brows((3, 0), (-2, -2))
            self._glasses((("open", 0, 0, 22, 26), ("half", 3, 0, 20, 12)), tilt=2 if wobble else 0)
            self._mouth("flat", width=14, shift=5 if wobble else 3)
            c.setFont(M5.Lcd.FONTS.Montserrat24)
            c.setTextSize(1)
            c.setTextColor(TEAL, BLACK)
            c.drawString("?", 113, 14 + (2 if wobble else 0))
            self._text(self.label or "No speech", 174, WHITE)
            self._text(self.detail or "Try again", 198, GREY, self.small)

        elif s == "sleeping":
            phase = key[1]
            breath = (0, 1, 2, 2, 1, 0, 0, 0)[phase]               # a slow breath: the face sinks and rises
            self._night = True
            self._head(dy=breath // 2, quiff=10, drop=8)
            self._brows((-1, 0), (-1, 0), dy=breath // 2)
            self._glasses((("closed", 0, 0, 22, 24), ("closed", 0, 0, 22, 24)), dy=breath // 2, tilt=-3)
            self._mouth("flat", dy=breath // 2, width=8 + breath * 2)
            self._night = False
            for i in range(min(3, phase // 2)):                    # up to three floating Z, growing
                size = 8 + 3 * i
                x0, y0 = 96 + 5 * i, 50 - 14 * i
                for d in (0, 1):
                    c.drawLine(x0, y0 + d, x0 + size, y0 + d, TEAL)
                    c.drawLine(x0 + size, y0 + d, x0, y0 + size + d, TEAL)
                    c.drawLine(x0, y0 + size + d, x0 + size, y0 + size + d, TEAL)

        elif s == "done":
            bob = key[1]
            self._head(quiff=2 if bob else -1)
            self._brows((2, 0), (2, 0))
            self._glasses((("happy", 0, 0, 22, 24), ("happy", 0, 0, 22, 24)))
            c.fillCircle(31, 133, 5, BLUSH)
            c.fillCircle(104, 133, 5, BLUSH)
            self._mouth("bigsmile")
            self._text(self.label or "Reply ready", 176, WHITE)
